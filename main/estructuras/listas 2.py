# funciones de listas
# append: añade un elemento al final de la lista
#  extend: añade varios elementos al final de la lista
#  insert: inserta un elemento en una posición específica
#  remove: elimina la primera ocurrencia de un elemento si hay varias y si no existe lanza un error
#  pop: elimina y devuelve el último elemento de la lista
#  clear: elimina todos los elementos de la lista
#  index: devuelve el índice de la primera ocurrencia de un elemento
#  count: devuelve el número de ocurrencias de un elemento
#  sort: ordena los elementos de la lista
#  reverse: invierte el orden de los elementos de la lista
#  copy: devuelve una copia superficial de la lista
#  len: devuelve el número de elementos de la lista

